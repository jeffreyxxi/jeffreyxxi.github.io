<h2 id="三、-路径与压力类指标-判断波动范围" tabindex="-1"><a class="header-anchor" href="#三、-路径与压力类指标-判断波动范围"><span>三、 路径与压力类指标（判断波动范围）</span></a></h2>
<p><strong>作用：</strong> 预判股价会在什么区间内波动。</p>
<h3 id="_5-boll-——-布林线" tabindex="-1"><a class="header-anchor" href="#_5-boll-——-布林线"><span>5. BOLL —— 布林线</span></a></h3>
<ul>
<li><strong>含义：</strong> 由上轨（压力）、中轨（平均）、下轨（支撑）组成的通道。</li>
<li><strong>核心信号：</strong>
<ul>
<li><strong>触碰上轨：</strong> 通常回落（除非主升浪）。</li>
<li><strong>触碰下轨：</strong> 通常反弹（短线抄底参考）。</li>
<li><strong>缩口（喇叭口变小）：</strong> 股价波动极小，正在蓄势 → <strong>预示即将变盘（暴涨或暴跌）</strong>。</li>
<li><strong>张口：</strong> 趋势确立，加速运行。</li>
</ul>
</li>
</ul>
<hr>
<h2 id="四、-筹码与成交量指标-看主力动向" tabindex="-1"><a class="header-anchor" href="#四、-筹码与成交量指标-看主力动向"><span>四、 筹码与成交量指标（看主力动向）</span></a></h2>
<p><strong>作用：</strong> 资金是最诚实的，“量在价先”。</p>
<h3 id="_6-vol-——-成交量" tabindex="-1"><a class="header-anchor" href="#_6-vol-——-成交量"><span>6. VOL —— 成交量</span></a></h3>
<ul>
<li><strong>含义：</strong> 真实的买卖手数。</li>
<li><strong>核心信号：</strong>
<ul>
<li><strong>量价齐升：</strong> 价格涨+量放大 → <strong>健康上涨，可跟</strong>。</li>
<li><strong>缩量下跌：</strong> 价格跌+量很小 → <strong>主力没跑（洗盘），不必恐慌</strong>。</li>
<li><strong>放量滞涨：</strong> 量巨大+价格不涨 → <strong>主力偷偷出货，极度危险</strong>。</li>
</ul>
</li>
</ul>
<h3 id="_7-cyq-——-筹码分布" tabindex="-1"><a class="header-anchor" href="#_7-cyq-——-筹码分布"><span>7. CYQ —— 筹码分布</span></a></h3>
<ul>
<li><strong>含义：</strong> 显示不同价格区间有多少人在持仓。</li>
<li><strong>核心信号：</strong>
<ul>
<li><strong>单峰密集：</strong> 筹码集中在窄幅区间，主力吸筹完成 → <strong>突破后爆发力强</strong>。</li>
<li><strong>上方长峰：</strong> 现价上方有大量筹码峰 → <strong>全是套牢盘，抛压大，难涨</strong>。</li>
<li><strong>获利比例99%：</strong> 大家都赚钱了 → <strong>容易引发获利盘抛售（见顶）</strong>。</li>
</ul>
</li>
</ul>
