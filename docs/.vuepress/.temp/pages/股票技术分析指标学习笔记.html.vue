<h2 id="一、-趋势类指标-判断股价大方向" tabindex="-1"><a class="header-anchor" href="#一、-趋势类指标-判断股价大方向"><span>一、 趋势类指标（判断股价大方向）</span></a></h2>
<p><strong>作用：</strong> 告诉你现在股票是在涨势中，还是跌势中。</p>
<h3 id="_1-ma-moving-average-——-移动平均线" tabindex="-1"><a class="header-anchor" href="#_1-ma-moving-average-——-移动平均线"><span>1. MA (Moving Average) —— 移动平均线</span></a></h3>
<ul>
<li><strong>含义：</strong> 过去一段时间市场的平均持仓成本（如5日、20日、60日线）。</li>
<li><strong>核心信号：</strong>
<ul>
<li><strong>支撑与压力：</strong> 股价回落至均线（如20日线）止跌 = <strong>支撑</strong>；股价反弹至均线受阻 = <strong>压力</strong>。</li>
<li><strong>多头排列：</strong> 短期均线 &gt; 长期均线（5日&gt;10日&gt;20日） = <strong>上升趋势（持股）</strong>。</li>
<li><strong>空头排列：</strong> 短期均线 &lt; 长期均线 = <strong>下跌趋势（观望）</strong>。</li>
<li><strong>金叉/死叉：</strong> 短期线上穿长期线为“金叉”（买点）；下穿为“死叉”（卖点）。</li>
</ul>
</li>
</ul>
<h3 id="_2-macd-——-异同移动平均线-指标之王" tabindex="-1"><a class="header-anchor" href="#_2-macd-——-异同移动平均线-指标之王"><span>2. MACD —— 异同移动平均线（指标之王）</span></a></h3>
<ul>
<li><strong>含义：</strong> 平滑后的趋势指标，主要看动能强弱。</li>
<li><strong>核心信号：</strong>
<ul>
<li><strong>零轴之上：</strong> 市场处于<strong>强势</strong>（牛市特征）。</li>
<li><strong>背离信号（最重要）：</strong>
<ul>
<li><strong>顶背离（卖点）：</strong> 股价创新高，但MACD红柱没创新高 → <strong>外强中干，看跌</strong>。</li>
<li><strong>底背离（买点）：</strong> 股价创新低，但MACD绿柱没创新低 → <strong>空头力竭，看涨</strong>。</li>
</ul>
</li>
</ul>
</li>
</ul>
<hr>
<h2 id="二、-超买超卖类指标-判断短期买卖点" tabindex="-1"><a class="header-anchor" href="#二、-超买超卖类指标-判断短期买卖点"><span>二、 超买超卖类指标（判断短期买卖点）</span></a></h2>
<p><strong>作用：</strong> 告诉你现在是不是涨过头了（该卖），或者跌过头了（该买）。</p>
<h3 id="_3-kdj-——-随机指标" tabindex="-1"><a class="header-anchor" href="#_3-kdj-——-随机指标"><span>3. KDJ —— 随机指标</span></a></h3>
<ul>
<li><strong>含义：</strong> 反应极灵敏的短线指标，适合做波段。</li>
<li><strong>核心信号：</strong>
<ul>
<li><strong>数值 &gt; 80（超买）：</strong> 买的人太多，随时可能回调 → <strong>卖出警戒</strong>。</li>
<li><strong>数值 &lt; 20（超卖）：</strong> 卖过头了，随时可能反弹 → <strong>短线买入</strong>。</li>
<li><strong>注意：</strong> 在单边暴涨/暴跌行情中，指标会长时间停在高位或低位（钝化），此时指标失灵。</li>
</ul>
</li>
</ul>
<h3 id="_4-rsi-——-相对强弱指标" tabindex="-1"><a class="header-anchor" href="#_4-rsi-——-相对强弱指标"><span>4. RSI —— 相对强弱指标</span></a></h3>
<ul>
<li><strong>含义：</strong> 买卖双方力量对比，比KDJ更稳定。</li>
<li><strong>核心信号：</strong>
<ul>
<li><strong>RSI &gt; 80：</strong> 市场过热，风险极高。</li>
<li><strong>RSI &lt; 20：</strong> 市场恐慌，机会出现。</li>
<li><strong>RSI = 50：</strong> 强弱平衡分界线。</li>
</ul>
</li>
</ul>
